'use client';

import { useCallback, useRef, useState } from 'react';
import { HardDrive, Lock } from 'lucide-react';
import { DemoBadge } from '@/components/ui/DemoBadge';
import { FounderAvatar } from '@/components/ui/FounderAvatar';
import { Skeleton } from '@/components/ui/Skeleton';
import { FOUNDERS } from '@/mocks';
import type { FounderId } from '@/types';
import { useFounderChat } from '../hooks/useFounderChat';
import { ChatComposer } from './ChatComposer';
import { ChatEmptyState } from './ChatEmptyState';
import { ChatErrorState } from './ChatErrorState';
import { ChatMessageList } from './ChatMessageList';

interface ChatPanelProps {
  projectId: string;
  /**
   * The founder whose private chat is shown. Render with `key={founderId}` so
   * switching founders remounts the panel and no draft or UI state carries over.
   */
  founderId: FounderId;
}

function HistorySkeleton() {
  return (
    <div className="flex-1 px-4 py-5 space-y-4" aria-busy="true" aria-label="Loading conversation">
      <Skeleton className="h-14 w-2/3 ml-auto rounded-2xl" />
      <Skeleton className="h-24 w-3/4 rounded-2xl" />
      <Skeleton className="h-10 w-1/2 ml-auto rounded-2xl" />
    </div>
  );
}

export function ChatPanel({ projectId, founderId }: ChatPanelProps) {
  const founder = FOUNDERS[founderId];
  const chat = useFounderChat(projectId, founderId);
  const isDemo = chat.mode === 'demo';

  const [draft, setDraft] = useState('');
  const textareaRef = useRef<HTMLTextAreaElement>(null);

  const handleSubmit = () => {
    if (chat.send(draft)) setDraft('');
  };

  const { takeFailed } = chat;
  const handleEdit = useCallback(
    (messageId: string) => {
      const content = takeFailed(messageId);
      if (content === undefined) return;
      // Don't clobber anything the user has typed since.
      setDraft((current) => (current.trim() ? `${current}\n${content}` : content));
      textareaRef.current?.focus();
    },
    [takeFailed],
  );

  const handleSelectPrompt = useCallback((prompt: string) => {
    setDraft(prompt);
    textareaRef.current?.focus();
  }, []);

  let body: React.ReactNode;
  if (chat.historyError) {
    body = <ChatErrorState error={chat.historyError} onRetry={chat.reloadHistory} />;
  } else if (chat.isLoadingHistory) {
    body = <HistorySkeleton />;
  } else if (chat.messages.length === 0) {
    body = (
      <div className="flex-1 min-h-0 overflow-y-auto">
        <ChatEmptyState onSelectPrompt={handleSelectPrompt} />
      </div>
    );
  } else {
    body = (
      <ChatMessageList
        messages={chat.messages}
        founderId={founderId}
        isDemo={isDemo}
        isAwaitingReply={chat.isAwaitingReply}
        onRetry={chat.retry}
        onEdit={handleEdit}
      />
    );
  }

  return (
    <section className="flex flex-col h-full min-h-0" aria-label={`${founder.name}'s private AI chat`}>
      {/* Header */}
      <header className="flex items-center justify-between gap-3 px-4 h-14 border-b border-[var(--color-border)] flex-shrink-0 bg-[var(--color-bg-base)]">
        <div className="flex items-center gap-3 min-w-0">
          <FounderAvatar founderId={founderId} size="md" />
          <div className="min-w-0">
            <div className="flex items-center gap-2">
              <span className="text-sm font-semibold text-[var(--color-text-primary)] truncate">{founder.name}</span>
              <span className="hidden sm:inline text-xs text-[var(--color-text-muted)]">— AI Workspace</span>
            </div>
            <div className="flex items-center gap-1.5 mt-0.5">
              <Lock className="w-3 h-3 text-[var(--color-secondary)] flex-shrink-0" />
              <span className="text-[10px] text-[var(--color-secondary)] font-medium truncate">
                Private — not shown to your co-founder
              </span>
            </div>
          </div>
        </div>

        {isDemo && (
          <div className="flex items-center gap-2 flex-shrink-0">
            <span
              className="hidden md:flex items-center gap-1 text-[10px] text-[var(--color-text-muted)]"
              title="Demo mode: messages are stored only in this browser's local storage. They are not saved to a server or synced across devices, and replies are scripted rather than generated by AI."
            >
              <HardDrive className="w-3 h-3" />
              Saved in this browser only
            </span>
            <DemoBadge />
          </div>
        )}
      </header>

      {body}

      <ChatComposer
        value={draft}
        onChange={setDraft}
        onSubmit={handleSubmit}
        isSending={chat.isAwaitingReply}
        disabled={chat.isLoadingHistory || Boolean(chat.historyError)}
        textareaRef={textareaRef}
      />
    </section>
  );
}
