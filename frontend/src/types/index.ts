// ─── Founders ───────────────────────────────────────────────

export type FounderId = 'founder-a' | 'founder-b';

export interface Founder {
  id: FounderId;
  name: string;
  avatar: string; // initials or URL
  color: string;  // CSS color or theme variable for the avatar accent
}

// ─── Project ────────────────────────────────────────────────

export interface Project {
  id: string;
  name: string;
  tagline: string;
  createdAt: string;
}

// ─── Chat Messages (L1 — private founder chat) ──────────────
// PROVISIONAL frontend shapes — not a finalized backend contract.
// A founder's messages must only ever be shown to that founder.

export type MessageRole = 'user' | 'assistant';

/** Client-side delivery state. Absent/'sent' = confirmed by the chat service. */
export type ChatMessageStatus = 'sending' | 'sent' | 'failed';

export interface ChatMessage {
  id: string;
  projectId: string;
  founderId: FounderId; // which founder's private session this belongs to
  role: MessageRole;
  content: string;
  createdAt: string; // ISO 8601
  status?: ChatMessageStatus;
}

export interface SendMessageRequest {
  content: string;
  /** Client-generated idempotency key; retries reuse the same value. */
  clientMessageId: string;
}

export interface SendMessageResult {
  userMessage: ChatMessage;
  assistantMessage: ChatMessage;
}

// ─── Shared Knowledge (L2) ──────────────────────────────────
// PROVISIONAL frontend shapes — no backend contract exists yet
// (docs/sync_contract.md is missing). Replace with the contract when agreed.
// L2 items are shared with both founders. They must never carry raw private
// (L1) transcript content beyond the approved supporting excerpt.

export const KNOWLEDGE_CATEGORIES = ['Problem', 'Target Customer', 'Market', 'Assumption', 'Evidence'] as const;
export type KnowledgeCategory = (typeof KNOWLEDGE_CATEGORIES)[number];

/**
 * How well-supported a finding is. These are NOT interchangeable:
 * - hypothesis: a founder's belief, not yet backed by evidence
 * - reported-evidence: a founder reports something they observed (e.g. interviews); not independently verified
 * - verified-evidence: independently verified — only where genuinely supported
 * - unverified-ai-claim: generated by the AI, not confirmed by anyone
 * - inconclusive: evidence is mixed or insufficient
 */
export const EPISTEMIC_STATUSES = [
  'hypothesis',
  'reported-evidence',
  'verified-evidence',
  'unverified-ai-claim',
  'inconclusive',
] as const;
export type EpistemicStatus = (typeof EPISTEMIC_STATUSES)[number];

export interface KnowledgeItem {
  id: string;
  projectId: string;
  category: KnowledgeCategory;
  /** The finding / claim text. */
  finding: string;
  contributorId: FounderId;
  contributorName: string;
  /**
   * Opaque provenance identifier for the source message. It is NOT a
   * permission to fetch that message — the source chat stays private.
   * null when the backend did not supply provenance.
   */
  sourceRef: string | null;
  /** Verbatim excerpt approved for sharing. null when none was shared. */
  supportingExcerpt: string | null;
  createdAt: string;
  epistemicStatus: EpistemicStatus;
}

/**
 * An explicit relationship between findings that may disagree. Both items
 * stay as separate records; the relationship never picks a winner.
 */
export interface KnowledgeConflict {
  id: string;
  projectId: string;
  itemIds: [string, string];
  /** Optional backend-supplied explanation. */
  explanation: string | null;
}

export interface SharedKnowledgeSnapshot {
  projectId: string;
  items: KnowledgeItem[];
  conflicts: KnowledgeConflict[];
}

// ─── Co-Founder Catch-Up (L2 summary) ───────────────────────

export type CatchUpFindingKind = 'discovery' | 'assumption' | 'conflict';

export interface CatchUpFinding {
  id: string;
  kind: CatchUpFindingKind;
  text: string;
  /** Every finding must reference at least one real shared knowledge item. */
  knowledgeItemIds: string[];
}

export interface CatchUpProposalRef {
  id: string;
  title: string;
}

export interface CatchUpSummary {
  projectId: string;
  requestingFounderId: FounderId;
  coFounderId: FounderId;
  coFounderName: string;
  summary: string;
  findings: CatchUpFinding[];
  /** Union of every knowledge item ID referenced by this summary. */
  knowledgeItemIds: string[];
  /** Proposals awaiting the requesting founder, when supplied. */
  pendingProposals?: CatchUpProposalRef[];
  coverage?: { itemCount: number; from?: string; to?: string };
  generatedAt?: string;
}

// ─── Decisions (L3) ─────────────────────────────────────────
// PROVISIONAL frontend shapes — no backend contract exists yet
// (docs/sync_contract.md is missing). The backend is authoritative for
// identity, approval validation, version checks, idempotence and commits.

export const PROPOSAL_STATUSES = ['DRAFT', 'PENDING_APPROVAL', 'CHANGES_REQUESTED', 'COMMITTED'] as const;
export type ProposalStatus = (typeof PROPOSAL_STATUSES)[number];

export type ApprovalDecision = 'APPROVED' | 'CHANGES_REQUESTED';

/**
 * One founder's decision on ONE specific proposal version. There is never a
 * shared "isApproved" flag: approval is per founder AND per version.
 */
export interface FounderApproval {
  founderId: FounderId;
  proposalId: string;
  version: number;
  decision: ApprovalDecision;
  /** Required when requesting changes. */
  reason: string | null;
  decidedAt: string;
}

/** Content fields a founder writes; versioned as a unit. */
export interface ProposalContent {
  title: string;
  direction: string;
  nextAction: string;
  supportingKnowledgeIds: string[];
  conflictingKnowledgeIds: string[];
}

/** Snapshot of a superseded version, kept for history. */
export interface ProposalVersion extends ProposalContent {
  version: number;
  createdAt: string;
  /** Note the proposer attached when publishing this version. */
  changeNote: string | null;
  /** Decisions recorded against this version before it was superseded. */
  approvals: FounderApproval[];
}

export interface DecisionProposal extends ProposalContent {
  id: string;
  projectId: string;
  createdByFounderId: FounderId;
  version: number;
  status: ProposalStatus;
  /** Decisions for the CURRENT version only; cleared when a new version is published. */
  approvals: FounderApproval[];
  changeNote: string | null;
  history: ProposalVersion[];
  /** Committed-state revision this proposal produced, once committed. */
  committedRevision: number | null;
  createdAt: string;
  updatedAt: string;
}

/**
 * A conflict surfaced on a proposal: a referenced conflicting finding, plus
 * the supporting finding it disagrees with when that relationship is known.
 * Derived only from supplied conflict data — never inferred by the frontend.
 */
export interface ProposalConflict {
  conflictingItemId: string;
  supportingItemId: string | null;
  knowledgeConflictId: string | null;
}

export interface CommittedDecision extends ProposalContent {
  proposalId: string;
  proposalVersion: number;
  approvedBy: { founderId: FounderId; approvedAt: string }[];
  committedAt: string;
}

/** The project's OFFICIAL direction. Changes only through a confirmed commit. */
export interface CommittedStartupState {
  projectId: string;
  /** 0 = nothing committed yet; increments by exactly 1 per commit. */
  revision: number;
  decision: CommittedDecision | null;
}

