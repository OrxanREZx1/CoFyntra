'use client';

import { BadgeCheck, Bot, CircleHelp, Lightbulb, Quote, type LucideIcon } from 'lucide-react';
import { cn } from '@/lib/utils';
import type { EpistemicStatus } from '@/types';

interface StatusMeta {
  label: string;
  /** Short label for very tight spaces. */
  shortLabel: string;
  description: string;
  icon: LucideIcon;
  className: string;
}

/** Each status has a distinct icon + label, so it never relies on color alone. */
export const EPISTEMIC_STATUS_META: Record<EpistemicStatus, StatusMeta> = {
  hypothesis: {
    label: 'Founder hypothesis',
    shortLabel: 'Hypothesis',
    description: "A founder's belief that hasn't been backed by evidence yet.",
    icon: Lightbulb,
    className: 'bg-[var(--color-primary-muted)] text-[var(--color-primary)] border-[var(--color-primary)]/20',
  },
  'reported-evidence': {
    label: 'Founder-reported evidence',
    shortLabel: 'Reported',
    description: 'Something a founder observed or heard directly (e.g. in interviews). Not independently verified.',
    icon: Quote,
    className: 'bg-[var(--color-secondary-muted)] text-[var(--color-secondary)] border-[var(--color-secondary)]/20',
  },
  'verified-evidence': {
    label: 'Verified evidence',
    shortLabel: 'Verified',
    description: 'Independently verified.',
    icon: BadgeCheck,
    className: 'bg-[var(--color-success-muted)] text-[var(--color-success)] border-[var(--color-success)]/20',
  },
  'unverified-ai-claim': {
    label: 'Unverified AI claim',
    shortLabel: 'AI claim',
    description: 'Generated by the AI assistant and not confirmed by anyone.',
    icon: Bot,
    className: 'bg-[var(--color-warning-muted)] text-[var(--color-warning)] border-[var(--color-warning)]/20',
  },
  inconclusive: {
    label: 'Inconclusive',
    shortLabel: 'Inconclusive',
    description: 'The available evidence is mixed or insufficient.',
    icon: CircleHelp,
    className: 'bg-[var(--color-bg-hover)] text-[var(--color-text-secondary)] border-[var(--color-border)]',
  },
};

interface EpistemicBadgeProps {
  status: EpistemicStatus;
  /** Use the short label (full label remains available to assistive tech). */
  compact?: boolean;
  className?: string;
}

export function EpistemicBadge({ status, compact = false, className }: EpistemicBadgeProps) {
  const meta = EPISTEMIC_STATUS_META[status];
  const Icon = meta.icon;
  return (
    <span
      className={cn(
        'inline-flex items-center gap-1 px-1.5 py-0.5 rounded-full text-[10px] font-medium border whitespace-nowrap',
        meta.className,
        className,
      )}
      title={`${meta.label}: ${meta.description}`}
    >
      <Icon className="w-2.5 h-2.5 flex-shrink-0" aria-hidden="true" />
      {compact ? (
        <>
          <span aria-hidden="true">{meta.shortLabel}</span>
          <span className="sr-only">{meta.label}</span>
        </>
      ) : (
        meta.label
      )}
    </span>
  );
}
